"""Render a :class:`~tickstack.bench.BenchResult` to Markdown + keep the JSON.

The report is written to be read by a skeptic. It leads with the correctness
summary (a benchmark of wrong answers is worthless), states the provenance
(versions, platform, dataset shape) inline, and only then shows timings. Every
speedup is DuckDB-vs-pandas *compute* (``duckdb_arrow`` vs ``pandas``) so I/O never
inflates it; the from-Parquet column is shown separately as what a cold query costs.
"""

from __future__ import annotations

from pathlib import Path

from .bench import QUERIES, BenchResult

_QUERY_LABELS = {
    "q1_asof": "Q1 as-of join (trades×quotes)",
    "q2_vwap": "Q2 VWAP + OHLCV bars",
    "q3_book": "Q3 book reconstruction",
    "q4_event": "Q4 event study",
    "q5_corr": "Q5 cross-symbol correlation",
}


def _cell(timings, query, engine, layout):
    for t in timings:
        if t.query == query and t.engine == engine and t.layout == layout:
            return t
    return None


def _fmt_ms(x: float | None) -> str:
    if x is None:
        return "—"
    if x >= 1000:
        return f"{x/1000:.2f} s"
    if x >= 10:
        return f"{x:.0f} ms"
    return f"{x:.1f} ms"


def _bytes_str(n: int) -> str:
    if n < 1024:
        return f"{n} B"
    if n < 1024**2:
        return f"{n/1024:.1f} KB"
    if n < 1024**3:
        return f"{n/1024**2:.1f} MB"
    return f"{n/1024**3:.2f} GB"


def render_markdown(res: BenchResult) -> str:
    m = res.meta
    cfg = m.get("config", {})
    ver = m.get("versions", {})
    gt = m.get("q3_ground_truth", {})
    layouts = m.get("layouts", [])
    lines: list[str] = []

    lines.append("# Benchmark results\n")
    lines.append(
        "Generated by `scripts/run_bench.py`. Every number below is reproducible "
        "from the committed seed; see the provenance block at the end.\n"
    )

    # --- Correctness first ---
    lines.append("## Correctness (gates everything below)\n")
    allok = all(res.correctness.values())
    lines.append(
        f"- **Engine agreement:** DuckDB and the pandas baseline return identical "
        f"results on all five queries: **{'PASS' if allok else 'FAIL'}** "
        f"({sum(res.correctness.values())}/{len(res.correctness)}).\n"
    )
    if gt:
        lines.append(
            f"- **Q3 ground truth:** reconstructing top-of-book from the market-by-price "
            f"stream at the generator's own quote timestamps reproduces the `quotes` table "
            f"exactly: **{gt.get('matched')}/{gt.get('total')}** timestamps.\n"
        )
    lines.append("")

    # --- Dataset shape ---
    lines.append("## Dataset\n")
    lines.append(
        f"- {cfg.get('n_days','?')} trading days × {len(cfg.get('symbols',[]))} symbols "
        f"× {cfg.get('events_per_symbol_day','?'):,} events/symbol/day (seed {cfg.get('seed','?')}).\n"
        if isinstance(cfg.get("events_per_symbol_day"), int) else
        f"- {cfg.get('n_days','?')} trading days × {len(cfg.get('symbols',[]))} symbols.\n"
    )
    lines.append(
        f"- Rows: **{res.rows.get('trades',0):,}** trades, "
        f"**{res.rows.get('quotes',0):,}** quotes, "
        f"**{res.rows.get('book_events',0):,}** book events.\n"
    )
    lines.append("")

    # --- Headline five-query table (best layout, arrow-vs-pandas) ---
    lines.append("## Five-query benchmark — DuckDB, ClickHouse, QuestDB vs pandas (compute)\n")
    lines.append(
        "Median of "
        f"{m.get('repeats','?')} timed runs after warmup, {m.get('threads','?')} threads, "
        "on the `sorted` layout, all engines querying data loaded once into their own "
        "in-memory format (native DuckDB/ClickHouse/QuestDB tables; pandas DataFrames) so this is compute "
        "only. Speedup = pandas ÷ DuckDB.\n"
    )
    best = "sorted" if "sorted" in layouts else layouts[0]
    lines.append("| Query | DuckDB | ClickHouse | QuestDB | pandas | Speedup (DuckDB) |")
    lines.append("|---|--:|--:|--:|--:|--:|")
    for q in QUERIES:
        d = _cell(res.timings, q, "duckdb_mem", best)
        ch = _cell(res.timings, q, "clickhouse", best)
        qdb = _cell(res.timings, q, "questdb", best)
        p = _cell(res.timings, q, "pandas", best)
        speed = (p.median_ms / d.median_ms) if (d and p and d.median_ms > 0) else None
        speed_s = f"{speed:.1f}×" if speed else "—"
        lines.append(
            f"| {_QUERY_LABELS[q]} | {_fmt_ms(d.median_ms if d else None)} "
            f"| {_fmt_ms(ch.median_ms if ch else None)} | {_fmt_ms(qdb.median_ms if qdb else None)} "
            f"| {_fmt_ms(p.median_ms if p else None)} | {speed_s} |"
        )
    lines.append("")

    # --- Layout experiment ---
    lines.append("## Layout experiment — same query, four physical layouts\n")
    lines.append(
        "DuckDB reading **from Parquet** each run (cold-query cost, so layout matters). "
        "Median ms per query per layout.\n"
    )
    header = "| Query | " + " | ".join(layouts) + " |"
    lines.append(header)
    lines.append("|---|" + "|".join(["--:"] * len(layouts)) + "|")
    for q in QUERIES:
        row = [f"| {_QUERY_LABELS[q]} "]
        for lay in layouts:
            c = _cell(res.timings, q, "duckdb_parquet", lay)
            row.append(f"| {_fmt_ms(c.median_ms if c else None)} ")
        lines.append("".join(row) + "|")
    lines.append("")

    # --- Scoped query: the honest, counterintuitive layout result ---
    if res.scoped_timings:
        lines.append("### Scoped query — one symbol, one day\n")
        lines.append(
            "The far more common desk query is \"pull one name for one day\" — an as-of "
            f"join scoped to a single symbol-day (**{res.scoped_meta.get('result_rows','?')}** "
            "result rows). The intuitive expectation is that `by_date_symbol` wins here "
            "by pruning to one file. It does not, and that is the point: at this scale a "
            "full scan is cheap, while directory partitioning adds per-file open "
            "overhead. `by_date_symbol` creates one small file per symbol-day, so it is "
            "the *slowest* — the small-files anti-pattern. Timed from Parquet, median ms.\n"
        )
        lines.append("| Query | " + " | ".join(layouts) + " |")
        lines.append("|---|" + "|".join(["--:"] * len(layouts)) + "|")
        row = ["| scoped as-of (1 symbol × 1 day) "]
        for lay in layouts:
            c = next((t for t in res.scoped_timings if t.layout == lay), None)
            row.append(f"| {_fmt_ms(c.median_ms if c else None)} ")
        lines.append("".join(row) + "|")
        lines.append(
            "\nThe scale-dependence is the migration lesson — see "
            "`scripts/run_partition_study.py` and `results/partition_study.md`, which "
            "sweep dataset size and show `by_date_symbol` getting *worse* as data grows "
            "while `sorted` (large files, symbol-clustered, statistics on) stays fast.\n"
        )
        lines.append("")

    # --- Storage sizes ---
    lines.append("### On-disk size by layout (ZSTD, same rows)\n")
    lines.append("| Layout | trades | quotes | book_events | total |")
    lines.append("|---|--:|--:|--:|--:|")
    for lay in layouts:
        s = res.sizes_bytes.get(lay, {})
        tot = sum(s.values())
        lines.append(
            f"| {lay} | {_bytes_str(s.get('trades',0))} | {_bytes_str(s.get('quotes',0))} "
            f"| {_bytes_str(s.get('book_events',0))} | {_bytes_str(tot)} |"
        )
    lines.append("")

    # --- One-time load cost (the honest counterpart to the compute table) ---
    if res.load_ms:
        lines.append("### One-time in-memory load (paid once per session, then amortized)\n")
        lines.append(
            "The compute table above excludes this by design: a research session loads "
            "the working set once and runs many queries against it. Shown so it is not "
            "hidden. Both figures are timed over the *same* work — read Parquet into "
            "Arrow, then materialize into the engine's own format (native DuckDB tables "
            "vs pandas DataFrames) — so the two columns are directly comparable and the "
            "shared Parquet read is charged to both, not to neither.\n"
        )
        lines.append("| Layout | DuckDB load | ClickHouse load | QuestDB load | pandas load |")
        lines.append("|---|--:|--:|--:|--:|")
        for lay in layouts:
            lm = res.load_ms.get(lay, {})
            lines.append(
                f"| {lay} | {_fmt_ms(lm.get('duckdb'))} | {_fmt_ms(lm.get('clickhouse'))} "
                f"| {_fmt_ms(lm.get('questdb'))} | {_fmt_ms(lm.get('pandas'))} |"
            )
        lines.append("")

    # --- Provenance ---
    lines.append("## Provenance\n")
    lines.append(f"- Platform: {m.get('platform','?')}")
    lines.append(
        "- Versions: "
        + ", ".join(f"{k} {v}" for k, v in ver.items())
    )
    lines.append(
        f"- Repeats: {m.get('repeats','?')} timed runs after 1 warmup; "
        f"threads: {m.get('threads','?')}."
    )
    lines.append("")
    return "\n".join(lines)


def write_reports(res: BenchResult, results_dir: Path) -> None:
    results_dir = Path(results_dir)
    results_dir.mkdir(parents=True, exist_ok=True)
    (results_dir / "benchmark.md").write_text(render_markdown(res))
